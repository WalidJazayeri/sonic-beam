constexpr int cell_w = 6, cell_h = 8, columns = 8, rows = 8;
constexpr int atlas_w = cell_w * columns, atlas_h = cell_h * rows;

inline int index_of(char c)
{
    if (c >= 'a' && c <= 'z') c = char(c - 32);
    const char *p = std::strchr(chars, c);
    return (c && p) ? int(p - chars) : -1;
}

inline void build_atlas(uint8_t *pixels)
{
    std::memset(pixels, 0, atlas_w * atlas_h);
    const int count = int(std::strlen(chars));
    for (int g = 0; g < count; ++g) {
        const int cx = (g % columns) * cell_w, cy = (g / columns) * cell_h;
        for (int y = 0; y < 7; ++y)
            for (int x = 0; x < 5; ++x)
                if (glyphs[g][y] & (0x10 >> x)) pixels[(cy + y) * atlas_w + cx + x] = 255;
    }
}

