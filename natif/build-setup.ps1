# Builds the player's setup: natif/installer + the converter + every file of natif/mod ->
# natif/build/SonicBeam-Setup-<version>.exe, one GUI exe (no admin rights) that installs the mod, converts Sonic
# from the player's own Sonic Frontiers and uninstalls both. Nothing from Sonic Frontiers goes into it.
# Same toolchain and flags as build-converter.ps1; generated sources go to natif/build/gen (git-ignored).
param([string]$Version = '')
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$repo = Split-Path -Parent $root
$zig = Join-Path $repo '.tools\zig-x86_64-windows-0.15.2\zig.exe'
$acl = Join-Path $repo '.tools\PXDAnimationTools-26fd823adcfba9d053b3ad0acac38aa0ae2086a3\FrontiersAnimDecompress\includes'
# Version: natif/VERSION (major.minor.patch), shown in the window and the exe's Properties
if (-not $Version) { $Version = (Get-Content (Join-Path $root 'VERSION') -Raw).Trim() }
if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw "Version '$Version' is not major.minor.patch" }
$major, $minor, $patch = $Version.Split('.') | ForEach-Object { [int]$_ }   # [int]: no leading zero (octal in C)
$out = Join-Path $root 'build'
$gen = Join-Path $out 'gen'
$installer = Join-Path $root 'installer'
New-Item -ItemType Directory -Force $gen | Out-Null
$utf8 = New-Object System.Text.UTF8Encoding $false   # no BOM: these files are included mid-file

# version.h: for setup.rc (numbers, narrow string) and setup.cpp (narrow and wide strings)
$versionLines = @(
    '// Generated by natif/build-setup.ps1 from natif/VERSION: do not edit.',
    '#ifndef SN_VERSION_H',
    '#define SN_VERSION_H',
    "#define SN_VER_MAJOR $major",
    "#define SN_VER_MINOR $minor",
    "#define SN_VER_PATCH $patch",
    "#define SN_VERSION_STR `"$Version`"",
    "#define SN_VERSION_WSTR L`"$Version`"",
    '#endif'
)
[IO.File]::WriteAllText((Join-Path $gen 'version.h'), ($versionLines -join "`n") + "`n", $utf8)

# A path as a C string literal: printable ASCII as is, any other UTF-8 byte as an octal escape
# (a hex escape would swallow the hex digits after it)
function ConvertTo-CString([string]$text) {
    $s = New-Object System.Text.StringBuilder
    foreach ($b in [Text.Encoding]::UTF8.GetBytes($text)) {
        if ($b -eq 0x22 -or $b -eq 0x5C) { [void]$s.Append('\').Append([char]$b) }
        elseif ($b -ge 0x20 -and $b -lt 0x7F) { [void]$s.Append([char]$b) }
        else { [void]$s.Append('\' + [Convert]::ToString([int]$b, 8).PadLeft(3, '0')) }
    }
    '"' + $s.ToString() + '"'
}

# mod_payload.inc: the files build.ps1 -Install mirrors, sorted, as byte arrays, then the kModFiles table.
# install.hpp includes it inside namespace setup, right after struct ModFile. 32 hex literals per line,
# one BitConverter call per line: quick to write and to compile.
$mod = Join-Path $root 'mod'
$files = [string[]]@(Get-ChildItem -Recurse -File $mod | ForEach-Object { $_.FullName.Substring($mod.Length + 1).Replace('\', '/') })
if ($files.Count -eq 0) { throw "no file in $mod" }
[Array]::Sort($files, [StringComparer]::Ordinal)
$payload = New-Object System.Text.StringBuilder
$table = New-Object System.Text.StringBuilder
[void]$payload.Append("// Generated by natif/build-setup.ps1 from natif/mod ($($files.Count) files): do not edit.`n")
[void]$payload.Append("// Included by natif/installer/install.hpp inside namespace setup, after struct ModFile.`n")
$total = 0
for ($i = 0; $i -lt $files.Count; ++$i) {
    $bytes = [IO.File]::ReadAllBytes((Join-Path $mod $files[$i]))
    $total += $bytes.Length
    [void]$payload.Append("static const unsigned char kModPayload$i[] = {`n")
    if ($bytes.Length -eq 0) { [void]$payload.Append("0x00,`n") }   # C++ has no empty array; the table says 0 bytes
    for ($at = 0; $at -lt $bytes.Length; $at += 32) {
        $n = [Math]::Min(32, $bytes.Length - $at)
        [void]$payload.Append('0x').Append([BitConverter]::ToString($bytes, $at, $n).Replace('-', ',0x')).Append(",`n")
    }
    [void]$payload.Append("};`n")
    [void]$table.Append("    {$(ConvertTo-CString $files[$i]), kModPayload$i, $($bytes.Length)},`n")
}
[void]$payload.Append("static const setup::ModFile kModFiles[] = {`n").Append($table.ToString()).Append("};`n")
[void]$payload.Append("static const size_t kModFileCount = $($files.Count);`n")
$payloadFile = Join-Path $gen 'mod_payload.inc'
[IO.File]::WriteAllText($payloadFile, $payload.ToString(), $utf8)
Write-Output ("payload: {0} files of natif\mod, {1} bytes -> {2}" -f $files.Count, $total, $payloadFile)

# zig writes warnings and errors to stderr: read them as text into the log, not as PowerShell errors
$log = Join-Path $out 'setup-compile.log'
New-Item -ItemType File -Force $log | Out-Null   # empty, and there even when zig says nothing
function Invoke-Zig([string[]]$zigArgs) {
    $global:LASTEXITCODE = 0
    & { $ErrorActionPreference = 'Continue'; & $zig @zigArgs 2>&1 } | ForEach-Object { "$_" } | Out-File -Append -Encoding utf8 $log
}
function Show-Errors([string]$what) {
    Get-Content $log | Select-String 'error' | Select-Object -First 40 | ForEach-Object Line
    throw "$what failed (see $log)"
}

# Resources: the manifest (asInvoker, Common Controls 6, per-monitor DPI, UTF-8) and the version block.
# Dash options: Git Bash rewrites "/fo" as a path.
$res = Join-Path $out 'setup.res'
Invoke-Zig @('rc', '-fo', $res, '-i', $gen, '-i', $installer, (Join-Path $installer 'setup.rc'))
if ($LASTEXITCODE -ne 0) { Show-Errors 'Resource compilation' }

# clHCA (sounds) is C, not C++: compiled on its own like build-converter.ps1 does, then linked
$clhca = Join-Path $out 'clhca.o'
Invoke-Zig @('cc', '-target', 'x86_64-windows-gnu', '-O2', '-c', (Join-Path $repo 'src\third_party\clhca\clhca.c'), '-o', $clhca)
if ($LASTEXITCODE -ne 0) { Show-Errors 'clHCA compilation' }

# The converter is linked in without its wmain (SONICNATIVE_NO_WMAIN): the setup calls sonicnative_convert_main.
# GUI subsystem with -municode: MinGW's start-up calls setup.cpp's wWinMain.
$sources = @((Join-Path $installer 'setup.cpp'), (Join-Path $root 'converter\main.cpp'), (Join-Path $repo 'src\frontiers\anim_acl.cpp'))
$exe = Join-Path $out "SonicBeam-Setup-$Version.exe"
Invoke-Zig (@('c++', '-target', 'x86_64-windows-gnu', '-std=c++17', '-O2', '-municode', '-fno-sanitize=undefined',
    '-Wno-missing-template-arg-list-after-template-kw', '-Wno-unused-command-line-argument',
    '-DSONICNATIVE_NO_WMAIN', "-DSONICNATIVE_VERSION=$Version", '-I', $acl, '-I', $gen) + $sources +
    @($clhca, $res, '-o', $exe, '-Wl,--subsystem,windows',
      '-lcomctl32', '-lole32', '-luuid', '-lshell32', '-ladvapi32', '-luser32', '-lgdi32'))
if ($LASTEXITCODE -ne 0) { Show-Errors 'Setup compilation' }
Get-Content $log | Select-String 'warning' | Select-Object -First 20 | ForEach-Object Line
Write-Output ("built {0} ({1} bytes)" -f $exe, (Get-Item $exe).Length)
Write-Output ("SHA256 {0}" -f (Get-FileHash -Algorithm SHA256 $exe).Hash)
